"""Every tuning configuration and its validation score (REPORT ONLY - it reproduces, not changes, the tuning).

Repeats the grid search of core/evaluate.py (tune_holdout) and records EVERY setting, not only the winner: each
candidate is fitted on the TRAINING set (preprocessing included) and scored by Uno's C on the VALIDATION set; AFT
distributions are chosen by AIC on the training set and their validation C is shown for reference. The locked test
set is never used. Checks that the best setting found here is the one recorded in artifacts/model_comparison.csv.

Writes artifacts/tuning_results.{csv,md}.
Run:  python -m core.tuning_results
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from core import evaluate, preprocess, splits
from core.models import make_model

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
TUNED = ("cox_ph", "cox_elasticnet", "deepsurv")


def run(out_dir: Path = ARTIFACTS) -> pd.DataFrame:
    train, valid = splits.load("train"), splits.load("validation")
    Xa, Xb, _ = preprocess.fit_transform_fold(train, valid)
    ya, yb = preprocess.sksurv_y(train), preprocess.sksurv_y(valid)
    tau = evaluate.truncation_tau(ya["time"])
    rows = []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for name in TUNED:
            for params in make_model(name).param_grid:
                try:
                    m = evaluate.fit_model(Xa, ya["time"], ya["event"], name, params, evaluate.SEED)
                    c = evaluate.uno_c(ya, yb, m.predict_risk(Xb), tau)
                except Exception:                     # a setting that fails to fit is shown, not hidden
                    c = np.nan
                rows.append({"model": name, "label": evaluate.LABELS[name], "params": json.dumps(params),
                             "aic": np.nan, "uno_c": c})
        for d in evaluate.AFT_DISTS:
            m = evaluate.fit_model(Xa, ya["time"], ya["event"], f"aft_{d}", {}, evaluate.SEED)
            rows.append({"model": "aft_best", "label": "AFT", "params": json.dumps({"distribution": d}),
                         "aic": float(m.aic), "uno_c": evaluate.uno_c(ya, yb, m.predict_risk(Xb), tau)})
    t = pd.DataFrame(rows)
    t["chosen"] = False
    for name, g in t.groupby("model"):
        best = g["aic"].idxmin() if name == "aft_best" else g["uno_c"].idxmax()
        t.loc[best, "chosen"] = True
    t["matches_main_analysis"] = t.apply(lambda r: _matches(r, out_dir), axis=1)
    t.to_csv(out_dir / "tuning_results.csv", index=False)
    (out_dir / "tuning_results.md").write_text(to_markdown(t, len(train), len(valid)), encoding="utf-8")
    return t


def _matches(r, out_dir: Path):
    """For the chosen rows: is this the setting recorded by the main analysis?"""
    if not r["chosen"]:
        return None
    comp = pd.read_csv(out_dir / "model_comparison.csv")
    recorded = json.loads(comp.loc[comp["model"] == r["model"], "tuned_params"].iloc[0])
    return recorded == json.loads(r["params"])


def _fmt_params(p: str) -> str:
    return ", ".join(f"{k} {v}" for k, v in json.loads(p).items())


def to_markdown(t: pd.DataFrame, n_train: int, n_valid: int) -> str:
    L = ["# Tuning results: every configuration (report only)", "",
         "_Generated by `python -m core.tuning_results` - do not edit by hand._", "",
         f"Every setting fitted on the training set ({n_train} graduates) and scored on the validation set "
         f"({n_valid} graduates); the test set is not used. **Chosen** = highest validation Uno's C (AFT: lowest AIC "
         "on the training set). The validation set is small, so differences of about 0.01 are within noise.", ""]
    for name in (*TUNED, "aft_best"):
        g = t[t["model"] == name]
        label = "AFT (distribution chosen by AIC)" if name == "aft_best" else g["label"].iloc[0]
        L += [f"## {label} ({len(g)} settings)", "",
              "| Setting | AIC (training) | Validation Uno's C | Chosen |" if name == "aft_best"
              else "| Setting | Validation Uno's C | Chosen |",
              "|---|---|---|---|" if name == "aft_best" else "|---|---|---|"]
        for _, r in g.sort_values("uno_c", ascending=False).iterrows():
            c = "failed to fit" if pd.isna(r["uno_c"]) else f"{r['uno_c']:.3f}"
            mark = "**yes**" if r["chosen"] else ""
            if name == "aft_best":
                L.append(f"| {_fmt_params(r['params'])} | {r['aic']:.1f} | {c} | {mark} |")
            else:
                L.append(f"| {_fmt_params(r['params'])} | {c} | {mark} |")
        chosen = g[g["chosen"]].iloc[0]
        L += ["", f"Chosen setting matches the main analysis (`model_comparison.csv`): "
              f"{'yes' if chosen['matches_main_analysis'] else 'NO - check'}.", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    t = run()
    print(t[t["chosen"]][["model", "params", "uno_c", "matches_main_analysis"]].to_string(index=False))
