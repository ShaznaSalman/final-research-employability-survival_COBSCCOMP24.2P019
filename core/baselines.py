"""Simple baselines for the selected model (REPORT ONLY - they do not change the selected model or the app).

How much do the questionnaire inputs add beyond the simplest predictors? Same fixed split as the main analysis
(core/splits.py; no data reuse): each baseline uses the selected model family (AFT log-normal), is fitted on the
TRAINING set and scored on the VALIDATION set; the locked test set is never used.
  - Kaplan-Meier (no model): the same curve for everyone, Uno's C = 0.5 by definition
  - GPA only
  - GPA + internship months (the two inputs clearly associated with the outcome in the main analysis)
  - core inputs (the eight core questionnaire inputs)
  - selected model (extended inputs, as in the main analysis)
Differences from the selected model use paired bootstrap resamples of the validation graduates (no refitting).

Writes artifacts/baselines.{json,md}.
Run:  python -m core.baselines
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np

from core import evaluate, preprocess, schema, splits

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
DISTRIBUTION = "lognormal"
N_BOOT = 1000
SETS = {
    "gpa_only": ("GPA only", {"gpa": "numeric"}),
    "gpa_internship": ("GPA + internship months", {"gpa": "numeric", "internship_months": "numeric"}),
    "core": ("Core inputs (8)", schema.CORE_FEATURES),
    "selected": ("Selected model (extended inputs)", None),
}


def run(out_dir: Path = ARTIFACTS) -> dict:
    train, valid = splits.load("train"), splits.load("validation")
    y_tr, y_va = preprocess.sksurv_y(train), preprocess.sksurv_y(valid)
    tau = evaluate.truncation_tau(y_tr["time"])
    risks = {}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for key, (_, feats) in SETS.items():
            pre, m = evaluate.fit_all(train, {}, DISTRIBUTION, "aft_best", evaluate.SEED, features=feats)
            risks[key] = m.predict_risk(pre.transform(valid))
    point = {k: evaluate.uno_c(y_tr, y_va, r, tau) for k, r in risks.items()}
    rng = np.random.default_rng(evaluate.SEED)
    boot = {k: [] for k in risks}
    for _ in range(N_BOOT):
        i = rng.integers(0, len(y_va), len(y_va))
        if y_va["event"][i].sum() < 2:
            continue
        for k, r in risks.items():
            boot[k].append(evaluate.uno_c(y_tr, y_va[i], r[i], tau))
    boot = {k: np.array(v) for k, v in boot.items()}
    rows = [{"model": "km", "label": "Kaplan-Meier (no model)", "uno_c": 0.5, "lo": None, "hi": None,
             "diff_vs_selected": round(0.5 - point["selected"], 4), "diff_lo": None, "diff_hi": None,
             "selected_better_share": None}]
    for k, (label, _) in SETS.items():
        d = boot["selected"] - boot[k]
        rows.append({"model": k, "label": label, "uno_c": point[k],
                     "lo": float(np.percentile(boot[k], 2.5)), "hi": float(np.percentile(boot[k], 97.5)),
                     "diff_vs_selected": point[k] - point["selected"],
                     "diff_lo": None if k == "selected" else float(np.percentile(-d, 2.5)),
                     "diff_hi": None if k == "selected" else float(np.percentile(-d, 97.5)),
                     "selected_better_share": None if k == "selected" else float((d > 0).mean())})
    res = {"n_train": len(train), "n_validation": len(valid), "bootstrap": int(len(boot["selected"])), "rows": rows}
    (out_dir / "baselines.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    (out_dir / "baselines.md").write_text(to_markdown(res), encoding="utf-8")
    return res


def to_markdown(r: dict) -> str:
    L = ["# Simple baselines (report only)", "",
         "_Generated by `python -m core.baselines` - do not edit by hand._", "",
         f"AFT log-normal with fewer inputs, fitted on the training set ({r['n_train']}) and scored on the validation "
         f"set ({r['n_validation']}); the test set is not used. Intervals and differences: {r['bootstrap']} paired "
         "bootstrap resamples of the validation graduates.", "",
         "| Model | Validation Uno's C (95% CI) | Difference from selected (95% CI) | Selected better in |",
         "|---|---|---|---|"]
    for x in r["rows"]:
        ci = "" if x["lo"] is None else f" ({x['lo']:.3f}-{x['hi']:.3f})"
        if x["model"] == "selected":
            diff, share = "-", "-"
        elif x["diff_lo"] is None:
            diff, share = f"{x['diff_vs_selected']:+.3f}", "-"
        else:
            diff = f"{x['diff_vs_selected']:+.3f} ({x['diff_lo']:+.3f} to {x['diff_hi']:+.3f})"
            share = f"{100 * x['selected_better_share']:.0f}%"
        L.append(f"| {x['label']} | {x['uno_c']:.3f}{ci} | {diff} | {share} |")
    g = next(x for x in r["rows"] if x["model"] == "gpa_only")
    L += ["", f"GPA alone reaches {g['uno_c']:.3f}; the other inputs add {-g['diff_vs_selected']:+.3f}. If an interval "
          "of a difference includes 0, the validation set cannot distinguish the two models."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    for x in run()["rows"]:
        print(f"{x['label']:35s} {x['uno_c']:.3f}  diff {x['diff_vs_selected']:+.3f}")
