"""Temporal validation: train on EARLIER completion cohorts, test on LATER ones.

A random split mixes cohorts, so it cannot show whether the model still works when the job market changes.
Respecting the fixed split (core/splits.py, no data reuse): every candidate model is fitted on TRAINING-set
graduates who completed in or before the training set's median completion month, and evaluated on VALIDATION-set
graduates who completed after it (rule fixed in advance). Hyperparameters are those chosen in the main analysis
(no tuning on the later cohorts). Later cohorts have shorter follow-up, so their calibration is checked only where
at least MIN_AT_RISK graduates are still under follow-up.

Run:  python -m core.temporal
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from lifelines import KaplanMeierFitter

from core import evaluate, splits
from core.clean import month_index

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
TRAIN_PATH = ROOT / "data" / "processed" / "graduates_train.csv"
INFO_PATH = ROOT / "data" / "processed" / "dataset_info.json"
MIN_AT_RISK = 10
MODELS = ("cox_ph", "cox_elasticnet", "aft_best", "deepsurv")


def split(train: pd.DataFrame, valid: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Earlier training-set cohorts vs later validation-set cohorts (cut = training-set median completion month)."""
    cut = int(np.median(month_index(train["graduation_date"])))
    label = f"{cut // 12}-{cut % 12 + 1:02d}"
    early = train[month_index(train["graduation_date"]) <= cut].reset_index(drop=True)
    late = valid[month_index(valid["graduation_date"]) > cut].reset_index(drop=True)
    return early, late, label


def main_params() -> dict:
    """Hyperparameters chosen on validation in the main analysis (artifacts/validation_metrics.csv)."""
    path = ARTIFACTS / "validation_metrics.csv"
    if not path.exists():
        return {}
    v = pd.read_csv(path)
    return {r["model"]: json.loads(r["params"]) for _, r in v.iterrows() if r["model"] in evaluate.TUNED}


def calibration(oof: pd.DataFrame, test: pd.DataFrame) -> list[dict]:
    """Mean predicted share employed vs Kaplan-Meier observed share, in the later cohorts."""
    km = KaplanMeierFitter().fit(test["duration_months"], test["event"])
    out = []
    for h in evaluate.CALIBRATION_HORIZONS:
        at_risk = int((test["duration_months"] >= h).sum())
        if at_risk < MIN_AT_RISK:
            continue
        obs = 1 - float(km.survival_function_at_times(h).iloc[0])
        pred = float((1 - oof[f"S_{h}"]).mean())
        out.append({"months": h, "predicted": pred, "observed": obs, "error": pred - obs, "at_risk": at_risk})
    return out


def run() -> dict:
    start = time.time()
    info = json.loads(INFO_PATH.read_text(encoding="utf-8"))
    early, test, cut = split(splits.load("train"), splits.load("validation"))
    params = main_params()
    rows_, oof, _ = evaluate.holdout(early, test, fixed_params=params or None)
    metrics = pd.DataFrame(rows_)
    metrics = metrics[metrics["model"].isin(MODELS)]
    cal = {m: calibration(oof[oof["model"] == m], test) for m in MODELS}
    cv = pd.read_csv(ARTIFACTS / "model_comparison.csv").set_index("model") \
        if (ARTIFACTS / "model_comparison.csv").exists() else None
    rows = []
    for _, r in metrics.iterrows():
        rows.append({"model": r["model"], "uno_c": r["uno_c"], "ibs": r["ibs"],
                     "uno_c_cv": float(cv.loc[r["model"], "uno_c_mean"]) if cv is not None and r["model"] in cv.index
                     else np.nan,
                     "max_abs_cal_error": max((abs(c["error"]) for c in cal[r["model"]]), default=np.nan)})
    table = pd.DataFrame(rows)
    table.to_csv(ARTIFACTS / "temporal_validation.csv", index=False)
    groups = {"earlier (training set)": early, "later (validation set)": test}
    md = render(table, cal, groups, cut, info, time.time() - start)
    (ARTIFACTS / "temporal_validation.md").write_text(md, encoding="utf-8")
    return {"cut": cut, "train_n": len(early), "test_n": len(test),
            "uno_c": {r["model"]: round(r["uno_c"], 3) for r in rows}}


def render(table, cal, groups, cut, info, runtime) -> str:
    L = ["# Temporal validation (earlier cohorts -> later cohorts)", "",
         "_Generated by `python -m core.temporal` - do not edit by hand._", ""]
    if info.get("is_synthetic", True):
        L += ["> **SYNTHETIC DATA - DEMO ONLY.** The synthetic data include a slower job market for graduates "
              "completing before 2025-01, so some drop in calibration is expected by design.", ""]
    L += [f"Fitted on training-set graduates who completed in or before **{cut}**; evaluated on validation-set "
          "graduates who completed after it (median of the training set, fixed in advance). No graduate is reused and "
          "the test set is not used; hyperparameters are those chosen on validation in the main analysis.", "",
          "| Cohorts | Completion months | N | Events | Median follow-up of those still looking |",
          "|---|---|---|---|---|"]
    for name, g in groups.items():
        cens = g.loc[g["event"] == 0, "duration_months"]
        L.append(f"| {name} | {g['graduation_date'].min()} to {g['graduation_date'].max()} | {len(g)} | "
                 f"{int(g['event'].sum())} | {cens.median():.0f} months |")
    L += ["", "## Discrimination and calibration on the later cohorts", "",
          "| Model | Uno's C (later cohorts) | Uno's C (whole validation set) | IBS | Largest calibration error |",
          "|---|---|---|---|---|"]
    for _, r in table.iterrows():
        cal_txt = "-" if np.isnan(r["max_abs_cal_error"]) else f"{r['max_abs_cal_error']:.3f}"
        L.append(f"| {evaluate.LABELS.get(r['model'], r['model'])} | {r['uno_c']:.3f} | {r['uno_c_cv']:.3f} | "
                 f"{r['ibs']:.3f} | {cal_txt} |")
    L += ["", "## Calibration detail (predicted vs observed share employed, later cohorts)", "",
          "| Model | Months | Predicted | Observed (KM) | Difference | Still followed |", "|---|---|---|---|---|---|"]
    for m, rows in cal.items():
        for c in rows:
            L.append(f"| {evaluate.LABELS.get(m, m)} | {c['months']} | {c['predicted']:.1%} | {c['observed']:.1%} | "
                     f"{c['error']:+.1%} | {c['at_risk']} |")
    L += ["", "A single split gives one estimate, and the later cohorts are small "
          "with short follow-up; treat differences of a few points in Uno's C as noise. A positive difference "
          "means the model trained on earlier cohorts predicted MORE graduates in work than were observed.", "",
          f"_Runtime: {runtime / 60:.1f} minutes._", ""]
    return "\n".join(L)


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
