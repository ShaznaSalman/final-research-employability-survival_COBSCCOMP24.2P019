"""Institution clustering: graduates from the same institution share recruiters, alumni networks and results-release
timing, so they are not fully independent. Ignoring this makes confidence intervals too narrow.

Two checks (unpenalised Cox on the model's design matrix):
  1. Cluster-robust (sandwich) standard errors by institution vs the usual standard errors.
  2. A Cox model STRATIFIED by institution (each institution its own baseline; type of institution drops out
     because it is constant within an institution) - do the other associations change?

Institution = the canonical name from the university lookup (name variants merged). Institutions are reported as
"Institution 1..k" (by size), never by name. With few institutions (< 30) the sandwich estimator itself is
imprecise, so the ratio of standard errors is a rough guide only.

Run:  python -m core.clustering
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from core import forms_adapter, inference, preprocess, splits
from core.clean import REFERENCE_DIR, find_input, load_institution_lookup

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
TRAIN_PATH = ROOT / "data" / "processed" / "graduates_train.csv"
INFO_PATH = ROOT / "data" / "processed" / "dataset_info.json"
FEW_CLUSTERS = 30


def institutions(df: pd.DataFrame, lookup: dict[str, str] | None = None) -> pd.Series:
    if lookup is None:
        lookup = load_institution_lookup(find_input("university_types", REFERENCE_DIR)[0])
    names = df["university_name"].map(forms_adapter.norm)
    return names.map(lambda n: lookup.get(n, n or "unknown"))


def run(df: pd.DataFrame | None = None, lookup: dict[str, str] | None = None, write: bool = True) -> dict:
    # training set only (core/splits.py): no graduate outside the training set is used to fit a model
    df = splits.load("train") if df is None else df.reset_index(drop=True)
    info = json.loads(INFO_PATH.read_text(encoding="utf-8")) if INFO_PATH.exists() else {}
    inst = institutions(df, lookup)
    sizes = inst.value_counts()
    alias = {name: f"Institution {i}" for i, name in enumerate(sizes.index, 1)}
    pre, X = inference.design(df)
    t, e = preprocess.outcome(df)

    naive = inference.hr_table(inference.fit_cox(X, t, e))
    robust = inference.hr_table(inference.fit_cox(X.assign(_inst=inst.to_numpy()), t, e, cluster_col="_inst"))
    keep = [c for c in X.columns if not c.startswith("university_type_")]
    strat = inference.hr_table(inference.fit_cox(X[keep].assign(_inst=inst.to_numpy()), t, e, strata=["_inst"]))

    tab = inference.finish(naive).merge(robust[["column", "se"]].rename(columns={"se": "se_robust"}), on="column")
    tab["se_ratio"] = tab["se_robust"] / tab["se"]
    tab["lo_robust"] = np.exp(tab["log_hr"] - inference.Z95 * tab["se_robust"])
    tab["hi_robust"] = np.exp(tab["log_hr"] + inference.Z95 * tab["se_robust"])
    st = inference.finish(strat).set_index("column")
    tab["stratified"] = tab["column"].map(lambda c: inference.fmt_hr(st.loc[c]) if c in st.index else "-")
    se_cons = np.maximum(tab["se"], tab["se_robust"])                  # few clusters: never narrower than usual
    tab["lo_cons"] = np.exp(tab["log_hr"] - inference.Z95 * se_cons)
    tab["hi_cons"] = np.exp(tab["log_hr"] + inference.Z95 * se_cons)
    excludes_1 = lambda lo, hi: (lo > 1) | (hi < 1)  # noqa: E731
    tab["changes_significance"] = excludes_1(tab["lo"], tab["hi"]) != excludes_1(tab["lo_cons"], tab["hi_cons"])
    groups = pd.DataFrame({"institution": inst.map(alias), "event": e}).groupby("institution", sort=False) \
        .agg(n=("event", "size"), events=("event", "sum")).reindex(list(alias.values()))
    out = {"institutions": len(sizes), "median_se_ratio": round(float(tab["se_ratio"].median()), 2),
           "max_se_ratio": round(float(tab["se_ratio"].max()), 2),
           "significance_changes": int(tab["changes_significance"].sum())}
    if write:
        tab.to_csv(ARTIFACTS / "institution_clustering.csv", index=False)
        (ARTIFACTS / "institution_clustering.md").write_text(render(tab, groups, out, info), encoding="utf-8")
    return out


def render(tab, groups, out, info) -> str:
    L = ["# Institution clustering", "", "_Generated by `python -m core.clustering` - do not edit by hand._", ""]
    if info.get("is_synthetic", True):
        L += ["> **SYNTHETIC DATA - DEMO ONLY.** The synthetic data have no institution-level effect beyond type "
              "and results-release timing, so little clustering is expected.", ""]
    L += [f"{out['institutions']} institutions (name variants merged). "
          + (f"**Fewer than {FEW_CLUSTERS} clusters: robust standard errors are themselves imprecise - treat the "
             "ratios as a rough guide.**" if out["institutions"] < FEW_CLUSTERS else ""), "",
          "| Institution | Graduates | Found IT work |", "|---|---|---|"]
    L += [f"| {name} | {r['n']} | {r['events']} |" for name, r in groups.iterrows()]
    L += ["", "## Standard errors with and without clustering by institution", "",
          "HR > 1: associated with finding work sooner (numeric features per one SD).", "",
          "| Feature | HR | 95% CI (usual) | 95% CI (cluster-robust) | SE ratio | Conservative 95% CI | "
          "Stratified by institution |", "|---|---|---|---|---|---|---|"]
    for _, r in tab.iterrows():
        flag = " *" if r["changes_significance"] else ""
        L.append(f"| {r['label']} | {r['hr']:.2f} | {r['lo']:.2f}-{r['hi']:.2f} | "
                 f"{r['lo_robust']:.2f}-{r['hi_robust']:.2f} | {r['se_ratio']:.2f} | "
                 f"{r['lo_cons']:.2f}-{r['hi_cons']:.2f}{flag} | {r['stratified']} |")
    L += ["", f"Median SE ratio {out['median_se_ratio']} (largest {out['max_se_ratio']}). A ratio above 1 means "
          "ignoring institutions understates uncertainty. A ratio below 1 is common with few clusters, because the "
          "sandwich estimator is biased downwards; it is NOT evidence of extra precision. The conservative CI "
          "therefore uses the larger of the two standard errors. "
          f"{out['significance_changes']} feature(s) change whether their conservative CI includes 1 (marked *).",
          "", "Names that match no entry in the university lookup are kept as their own institution; add them to "
          "the lookup (`institution` column) to merge them.", "",
          "The stratified model lets each institution have its own baseline time to employment; if the other "
          "hazard ratios stay similar, the associations are not explained by which institution graduates attended. "
          "Type of institution cannot be estimated in this model (it is constant within an institution).", ""]
    return "\n".join(L)


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
