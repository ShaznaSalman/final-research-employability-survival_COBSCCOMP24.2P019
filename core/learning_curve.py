"""Learning curve for the selected model (REPORT ONLY - it does not change the selected model or the app).

Asks whether more respondents answering the same questions would improve discrimination, using the SAME fixed split
as the main analysis (core/splits.py; no data reuse): the selected AFT Log-Normal model is fitted on random subsets
of 25%, 50% and 75% of the TRAINING set (N_SUBSAMPLES subsets each, fixed seeds) and on the whole training set, and
each fit is scored (Uno's C) on the VALIDATION set. The locked test set is never used. Preprocessing is fitted on each
subset only, and Uno's C uses that subset's censoring distribution and truncation point, as in core/evaluate.py.

Writes artifacts/learning_curve.{json,md}.
Run:  python -m core.learning_curve
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import matplotlib
import numpy as np

from core import evaluate, preprocess, splits

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
FRACTIONS = (0.25, 0.5, 0.75, 1.0)
N_SUBSAMPLES = 20
DISTRIBUTION = "lognormal"            # the selected model (artifacts/selection.json)


def score(sub, valid) -> float:
    """Fit the selected model on `sub` (preprocessing included) and return its validation Uno's C."""
    pre, model = evaluate.fit_all(sub, {}, DISTRIBUTION, "aft_best", evaluate.SEED)
    y_tr, y_va = preprocess.sksurv_y(sub), preprocess.sksurv_y(valid)
    risk = model.predict_risk(pre.transform(valid))
    return evaluate.uno_c(y_tr, y_va, risk, evaluate.truncation_tau(y_tr["time"]))


def run(out_dir: Path = ARTIFACTS) -> dict:
    train, valid = splits.load("train"), splits.load("validation")
    rows = []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for frac in FRACTIONS:
            reps = 1 if frac == 1.0 else N_SUBSAMPLES
            scores = [score(train if frac == 1.0 else train.sample(frac=frac, random_state=evaluate.SEED + r), valid)
                      for r in range(reps)]
            rows.append({"fraction": frac, "n_train": int(round(len(train) * frac)), "subsamples": reps,
                         "uno_c_mean": float(np.mean(scores)), "uno_c_min": float(np.min(scores)),
                         "uno_c_max": float(np.max(scores))})
    result = {"model": "AFT Log-Normal", "n_train": len(train), "n_validation": len(valid), "curve": rows}
    out_dir.mkdir(parents=True, exist_ok=True)
    plot(result, out_dir / "figures" / "learning_curve.png")
    (out_dir / "learning_curve.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    (out_dir / "learning_curve.md").write_text(to_markdown(result), encoding="utf-8")
    return result


def plot(r: dict, path: Path):
    c = r["curve"]
    n = np.array([x["n_train"] for x in c])
    mean, lo, hi = (np.array([x[k] for x in c]) for k in ("uno_c_mean", "uno_c_min", "uno_c_max"))
    fig, ax = plt.subplots(figsize=(7, 3.8), facecolor=evaluate.SURFACE)
    evaluate._style(ax)
    ax.fill_between(n, lo, hi, color=evaluate.ACCENT_LIGHT, alpha=0.5, linewidth=0,
                    label=f"Range over {N_SUBSAMPLES} random subsets")
    ax.plot(n, mean, "o-", color=evaluate.ACCENT, linewidth=2, markersize=7, markeredgecolor=evaluate.SURFACE,
            markeredgewidth=2, label="Mean validation Uno's C")
    for x, y in zip(n, mean):
        ax.annotate(f"{y:.3f}", (x, y), textcoords="offset points", xytext=(0, 9), ha="center", fontsize=8,
                    color=evaluate.INK)
    ax.set_xticks(n, [f"{x}\n({100 * f['fraction']:.0f}%)" for x, f in zip(n, c)])
    ax.set_xlabel("Training graduates used (share of the training set)", fontsize=9, color=evaluate.INK_MUTED)
    ax.set_ylabel("Uno's C on the validation set", fontsize=9, color=evaluate.INK_MUTED)
    ax.set_title(f"Learning curve of the selected model ({r['model']})", fontsize=11, color=evaluate.INK, loc="left")
    ax.legend(frameon=False, fontsize=8, loc="lower right")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, facecolor=evaluate.SURFACE)
    plt.close(fig)


def to_markdown(r: dict) -> str:
    L = ["# Learning curve (report only)", "",
         "_Generated by `python -m core.learning_curve` - do not edit by hand._", "",
         f"The selected model ({r['model']}) fitted on random subsets of the training set ({r['n_train']} graduates) "
         f"and scored on the validation set ({r['n_validation']} graduates); the test set is not used. Each smaller "
         f"size is the mean of {N_SUBSAMPLES} random subsets (fixed seeds), with the lowest and highest value.", "",
         "| Share of training set | Graduates | Validation Uno's C (mean) | Range |", "|---|---|---|---|"]
    for c in r["curve"]:
        rng = "-" if c["subsamples"] == 1 else f"{c['uno_c_min']:.3f}-{c['uno_c_max']:.3f}"
        L.append(f"| {100 * c['fraction']:.0f}% | {c['n_train']} | {c['uno_c_mean']:.3f} | {rng} |")
    gains = [b["uno_c_mean"] - a["uno_c_mean"] for a, b in zip(r["curve"], r["curve"][1:])]
    L += ["", "Gain at each step: " + ", ".join(f"{g:+.3f}" for g in gains) + ". A shrinking gain means more "
          "respondents answering the same questions would add little; the validation set is small, so treat "
          "differences of about 0.01 as noise."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    for c in run()["curve"]:
        print(f"{100 * c['fraction']:>3.0f}%  n={c['n_train']:<4d} Uno's C {c['uno_c_mean']:.3f}")
