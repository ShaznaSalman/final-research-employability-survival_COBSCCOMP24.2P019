"""Sample compared with published Sri Lankan figures (REPORT ONLY - descriptive; nothing here changes the model).

How representative is the sample? The modelling graduates (all roles; descriptive only) are compared with the
published figures already used to calibrate the synthetic data (core/synthetic.py ANCHORS; sources in
docs/synthetic_data.md): University of Kelaniya (2022) graduate employability survey and ICTA (2019) IT-BPM workforce
survey. The published figures cover other populations (all faculties of one university; the ICT workforce), so the
comparison shows direction, not a formal test.

Writes artifacts/sample_comparison.{json,md}.
Run:  python -m core.sample_comparison
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from lifelines import KaplanMeierFitter

from core import schema, splits
from core.synthetic import ANCHORS

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"


def compare(df: pd.DataFrame) -> list[dict]:
    employed = df[df["event"] == 1]
    after = employed[employed["duration_months"] > schema.JOB_BEFORE_GRADUATION_MONTHS]
    gave_gender = df[df["gender"].isin(["female", "male"])]
    km = KaplanMeierFitter().fit(df["duration_months"], df["event"])
    sample = {
        "female_share_pct": (100 * (gave_gender["gender"] == "female").mean(), len(gave_gender),
                             "women among graduates who gave female or male"),
        "mean_months_after_completion": (after["duration_months"].mean(), len(after),
                                         "mean months to the first IT job, graduates employed after completion "
                                         "(no minimum follow-up; recent cohorts' long searches are not yet observed)"),
        "employed_before_completion_pct": (100 * (employed["duration_months"]
                                                  <= schema.JOB_BEFORE_GRADUATION_MONTHS).mean(), len(employed),
                                           "share of employed graduates whose IT job began at or before completion"),
        "employed_at_survey_pct": (100 * df["event"].mean(), len(df), "share in an IT job at the survey"),
    }
    rows = []
    for key, (published, _lo, _hi, source) in ANCHORS.items():
        v, n, definition = sample[key]
        rows.append({"measure": key, "sample": round(float(v), 1), "n": int(n), "published": published,
                     "difference": round(float(v) - published, 1), "definition": definition,
                     "source": source.split(" (synthetic")[0]})
    rows.append({"measure": "km_median_months", "sample": float(km.median_survival_time_), "n": len(df),
                 "published": None, "difference": None,
                 "definition": "Kaplan-Meier median months to the first IT job (accounts for graduates still searching)",
                 "source": "-"})
    return rows


LABELS = {"female_share_pct": "Women (%)", "mean_months_after_completion": "Mean months to first job",
          "employed_before_completion_pct": "Employed graduates hired by completion (%)",
          "employed_at_survey_pct": "In an IT job at the survey (%)", "km_median_months": "Median months (Kaplan-Meier)"}


def run(out_dir: Path = ARTIFACTS) -> list[dict]:
    rows = compare(pd.read_csv(splits.TRAIN_PATH))
    (out_dir / "sample_comparison.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    (out_dir / "sample_comparison.md").write_text(to_markdown(rows), encoding="utf-8")
    return rows


def to_markdown(rows: list[dict]) -> str:
    L = ["# Sample compared with published Sri Lankan figures (report only)", "",
         "_Generated by `python -m core.sample_comparison` - do not edit by hand._", "",
         "All modelling graduates (descriptive). The published figures describe other populations, so differences show "
         "direction only.", "",
         "| Measure | Sample | n | Published | Difference | Published source | Sample definition |",
         "|---|---|---|---|---|---|---|"]
    for r in rows:
        pub = "-" if r["published"] is None else f"{r['published']:g}"
        dif = "-" if r["difference"] is None else f"{r['difference']:+.1f}"
        L.append(f"| {LABELS[r['measure']]} | {r['sample']:g} | {r['n']} | {pub} | {dif} | {r['source']} | "
                 f"{r['definition']} |")
    close = [LABELS[r["measure"]].lower() for r in rows
             if r["measure"].endswith("_pct") and abs(r["difference"]) <= 5]
    if close:
        L += ["", "Close to the published figures (within 5 percentage points): " + "; ".join(close) + "."]
    L += ["", "The sample found IT work sooner and more often than the published all-faculty figures. Part of this is "
          "real (IT graduates are expected to do better than all disciplines) and part is likely selection: a "
          "voluntary survey shared through personal and university networks tends to reach graduates who found work, "
          "and recent cohorts' long searches are not yet observed. This supports reading the results for this "
          "non-probability sample, not for all Sri Lankan IT graduates."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    for r in run():
        print(f"{LABELS[r['measure']]:45s} sample {r['sample']:>6g}  published {r['published']}")
