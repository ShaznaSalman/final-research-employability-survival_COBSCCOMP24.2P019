"""DeepSurv training curves (REPORT ONLY - they do not change the selected model or the app).

Shows how the DeepSurv candidate was trained and where early stopping ended training. DeepSurv is fitted on the
TRAINING set with the hyperparameters chosen on validation (artifacts/model_comparison.csv), exactly as in
core/evaluate.py: inside the training set, 20% of graduates are held out (stratified by event) to monitor the loss,
and training stops after `patience` epochs without improvement, keeping the best weights. The validation and test sets
are not used here.

Writes artifacts/deepsurv_curves.{json,md} and artifacts/figures/deepsurv_loss.png.
Run:  python -m core.deepsurv_curves
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

from core import evaluate, preprocess, splits
from core.models.deepsurv import DeepSurvModel

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"


def tuned_params(path: Path = ARTIFACTS / "model_comparison.csv") -> dict:
    """DeepSurv hyperparameters chosen on the validation set in the main analysis."""
    comp = pd.read_csv(path)
    return json.loads(comp.loc[comp["model"] == "deepsurv", "tuned_params"].iloc[0])


def run(out_dir: Path = ARTIFACTS) -> dict:
    train = splits.load("train")
    params = tuned_params(out_dir / "model_comparison.csv")
    pre = preprocess.build_preprocessor().fit(train)
    t, e = preprocess.outcome(train)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        model = DeepSurvModel(seed=evaluate.SEED, **params).fit(pre.transform(train), t, e)
    log = model.model_.log.to_pandas().reset_index(drop=True)
    best = int(log["val_loss"].idxmin())
    res = {"params": params, "patience": model.patience, "max_epochs": model.epochs, "epochs_run": len(log),
           "best_epoch": best + 1, "train_loss_best": float(log["train_loss"].iloc[best]),
           "val_loss_best": float(log["val_loss"].iloc[best]),
           "train_loss": log["train_loss"].round(4).tolist(), "val_loss": log["val_loss"].round(4).tolist()}
    plot(log, best, res, out_dir / "figures" / "deepsurv_loss.png")
    (out_dir / "deepsurv_curves.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    (out_dir / "deepsurv_curves.md").write_text(to_markdown(res), encoding="utf-8")
    return res


def plot(log: pd.DataFrame, best: int, res: dict, path: Path):
    """Two panels with their own y-scales: the two losses are averaged over different group sizes (training batches
    of 32 vs the whole hold-out), and the Cox loss grows with group size, so only their trends are comparable."""
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), facecolor=evaluate.SURFACE)
    epochs = np.arange(1, len(log) + 1)
    for ax, col, color, title in ((axes[0], "train_loss", evaluate.ACCENT, "Training loss (batches of 32)"),
                                  (axes[1], "val_loss", evaluate.INK_MUTED, "Early-stopping hold-out loss")):
        evaluate._style(ax)
        ax.plot(epochs, log[col], color=color, linewidth=2)
        ax.axvline(best + 1, color=evaluate.INK_MUTED, linestyle="--", linewidth=1)
        ax.set_title(title, fontsize=10, color=evaluate.INK, loc="left")
        ax.set_xlabel("Epoch", fontsize=9, color=evaluate.INK_MUTED)
    axes[0].set_ylabel("Cox partial-likelihood loss", fontsize=9, color=evaluate.INK_MUTED)
    for ax in axes:
        ax.annotate(f"best epoch {best + 1}\n(weights kept)", (best + 1, 1), xycoords=("data", "axes fraction"),
                    textcoords="offset points", xytext=(6, -24), fontsize=8, color=evaluate.INK)
    fig.suptitle("DeepSurv training on the training set (20% held out for early stopping)", x=0.01, ha="left",
                 fontsize=11, color=evaluate.INK)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, facecolor=evaluate.SURFACE)
    plt.close(fig)


def to_markdown(r: dict) -> str:
    p = r["params"]
    return "\n".join([
        "# DeepSurv training curves (report only)", "",
        "_Generated by `python -m core.deepsurv_curves` - do not edit by hand._", "",
        f"DeepSurv with the settings chosen on the validation set (width {p['width']}, {p['layers']} hidden "
        f"layer(s), dropout {p['dropout']}, learning rate {p['lr']}, Adam with weight decay 1e-4, batch size 32), "
        "fitted on the training set; 20% of the training graduates are held out to monitor the loss. The validation "
        "and test sets are not used.", "",
        f"- Training ran for **{r['epochs_run']} epochs** (maximum {r['max_epochs']}); the hold-out loss was lowest at "
        f"**epoch {r['best_epoch']}**, and training stopped {r['patience']} epochs later without improvement.",
        f"- Training loss fell from {r['train_loss'][0]:.3f} to {r['train_loss'][-1]:.3f}, while the hold-out loss "
        f"was lowest at epoch {r['best_epoch']} ({r['val_loss_best']:.3f}) and then rose to {r['val_loss'][-1]:.3f}: "
        "after the first epochs the network fitted the training graduates better without predicting new ones better "
        "(overfitting).",
        "- The weights from the best epoch are kept, so the overfitted later epochs do not reach the model.",
        "- The two losses are not on the same scale (the Cox loss grows with the number of graduates it is computed "
        "over: batches of 32 for training, the whole hold-out for early stopping); compare their trends, not their "
        "levels. That the best epoch comes so early is consistent with the small sample and weak signal: the "
        "network learns what the questionnaire inputs can tell it almost at once.", "",
        "Figure: `figures/deepsurv_loss.png`.", ""])


if __name__ == "__main__":
    r = run()
    print(f"epochs run {r['epochs_run']}, best epoch {r['best_epoch']}")
